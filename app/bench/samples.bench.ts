/**
 * Sample routes per mode between well-known public places in Lyon, for tuning and for the
 * progress notes. Run: npm run samples   (writes docs/SAMPLE_ROUTES.md)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { it } from "vitest";
import { Graph, type LonLat } from "../src/graph/graph";
import { FeatureIndex } from "../src/modes/features";
import { MODE_IDS, MODES } from "../src/modes/modes";
import { planMode } from "../src/modes/plan-mode";
import { minutes } from "../src/modes/stats";
import { Router } from "../src/router/astar";
import { NodeIndex } from "../src/router/snap";

/** Public squares and landmarks (approximate coordinates; snapped to the nearest path). */
export const SAMPLE_PLACES: Record<string, LonLat> = {
  "Place Bellecour": [4.8320, 45.7578],
  "Place des Terreaux": [4.8336, 45.7675],
  "Gare Part-Dieu": [4.8593, 45.7606],
  "Cathédrale Saint-Jean": [4.8274, 45.7606],
  "Place de la Croix-Rousse": [4.8317, 45.7745],
  "Basilique de Fourvière": [4.8225, 45.7623],
  "Parc de la Tête d'Or (Porte des Enfants du Rhône)": [4.8519, 45.7703],
  "Place Jean Macé": [4.8424, 45.7457],
};

export const SAMPLE_PAIRS: [string, string][] = [
  ["Place Bellecour", "Place des Terreaux"],
  ["Gare Part-Dieu", "Cathédrale Saint-Jean"],
  ["Place des Terreaux", "Place de la Croix-Rousse"],
  ["Cathédrale Saint-Jean", "Basilique de Fourvière"],
  ["Parc de la Tête d'Or (Porte des Enfants du Rhône)", "Place Bellecour"],
  ["Place Jean Macé", "Place Bellecour"],
];

it("sample routes", () => {
  const buf = readFileSync("app/public/data/lyon/graph.bin");
  const g = Graph.fromBuffer(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const router = new Router(g);
  const fi = new FeatureIndex(g);
  const index = new NodeIndex(g);
  const node = (name: string) => {
    const n = index.nearest(SAMPLE_PLACES[name]!);
    if (n === null) throw new Error(`can't snap ${name}`);
    return n;
  };

  const lines = [
    "# Sample routes",
    "",
    "Generated by `npm run samples` from the committed Lyon graph. Don't edit by hand.",
    "",
    "Each row is one mode between two public places: the cost of fun, which strategy won (the mode's cost profile, or collecting features via waypoints), and planning time on the build machine.",
    "",
  ];
  const timings: number[] = [];
  for (const [from, to] of SAMPLE_PAIRS) {
    lines.push(`## ${from} → ${to}`, "", "| Mode | Cost of fun | Strategy | Plan |", "|---|---|---|---:|");
    for (const id of MODE_IDS) {
      const t0 = performance.now();
      const p = planMode(router, fi, node(from), node(to), id, 7);
      const ms = performance.now() - t0;
      timings.push(ms);
      if (!p) {
        lines.push(`| ${MODES[id].name} | no route | | |`);
        continue;
      }
      const s = p.betterStats;
      const detail = [
        `${(s.lengthM / 1000).toFixed(1)} km`,
        `+${minutes(p.better.timeS) - minutes(p.normal.timeS)} min`,
        `${Math.round(s.climbM)} m up`,
        `trail ${Math.round(s.trailShare * 100)}%`,
        `turns ${s.leftTurns}L/${s.rightTurns}R`,
        s.retracedM >= 20 ? `${Math.round((s.retracedM / s.lengthM) * 100)}% doubled back` : "",
        s.underBuildings ? `${s.underBuildings} under a building` : "",
        s.mayClose.length ? `${s.mayClose.length} may close` : "",
      ].filter(Boolean);
      lines.push(`| ${MODES[id].name} | ${p.summary} <br><sub>${detail.join(" · ")}</sub> | ${p.strategy} | ${ms.toFixed(0)} ms |`);
    }
    lines.push("");
  }
  timings.sort((a, b) => a - b);
  const q = (p: number) => timings[Math.floor(p * (timings.length - 1))]!.toFixed(0);
  lines.push(`Planning time over all ${timings.length} plans: median ${q(0.5)} ms, p90 ${q(0.9)} ms, max ${q(1)} ms.`, "");
  writeFileSync("docs/SAMPLE_ROUTES.md", lines.join("\n"));
  console.log(lines.join("\n"));
});
