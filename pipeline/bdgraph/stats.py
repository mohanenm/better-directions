"""Graph stats report: edges by type, connectivity, passages, stairs, park paths, exclusions.

Written next to the city's SOURCE.md as stats.json (machine-readable, deterministic) and
STATS.md (for people)."""

from __future__ import annotations

import gzip
import json
from collections import Counter
from pathlib import Path

from bdgraph.build import Graph
from bdgraph.decode import decode_graph
from bdgraph.encode import FLAG_MAY_CLOSE, FLAG_STEPS_ESTIMATED, FLAG_THROUGH_BUILDING

UNPAVED = frozenset({
    "unpaved", "dirt", "earth", "ground", "gravel", "fine_gravel", "compacted", "grass", "mud",
    "sand", "woodchips", "pebblestone", "rock",
})  # fmt: skip


def compute_stats(graph: Graph, blob: bytes) -> dict:
    g = decode_graph(blob)
    meta = g.meta
    tagsets, areas = meta["tagsets"], meta["areas"]
    n_edges = meta["counts"]["edges"]

    by_kind: Counter[str] = Counter()
    km_by_kind: Counter[str] = Counter()
    feat = Counter()
    km = Counter()
    parks, passage_buildings = set(), set()
    total_km = 0.0
    for e in range(n_edges):
        tags = tagsets[g["way_tagset"][g["edge_way"][e]]]
        length_km = g["edge_length_m"][e] / 1000
        total_km += length_km
        hw = tags.get("highway", "?")
        by_kind[hw] += 1
        km_by_kind[hw] += length_km
        flags = g["edge_flags"][e]

        def count(name: str, *, _flags=flags, _len=length_km) -> None:
            feat[name] += 1
            km[name] += _len

        if tags.get("tunnel") == "building_passage":
            count("building_passage")
        if hw == "corridor" or tags.get("indoor") == "corridor":
            count("corridor")
        if tags.get("covered") == "yes":
            count("covered")
        if flags & FLAG_THROUGH_BUILDING:
            count("through_building")
            passage_buildings.add(g["edge_building"][e])
        if flags & FLAG_MAY_CLOSE:
            count("may_close")
        if hw == "steps":
            count("steps")
            feat["steps_total"] += g["edge_steps"][e]
            if flags & FLAG_STEPS_ESTIMATED:
                feat["steps_estimated_edges"] += 1
        if g["edge_park"][e]:
            count("park_path")
            parks.add(g["edge_park"][e])
        if tags.get("surface") in UNPAVED:
            count("unpaved")
        if tags.get("lit") == "yes":
            count("lit")
        if tags.get("informal") == "yes":
            count("informal")

    venue_ids = {g["edge_venue"][e] for e in range(n_edges)} - {0}
    venues = Counter(areas[v]["kind"] for v in venue_ids)

    return {
        "city": meta["city"]["id"],
        "graph": {
            "nodes": meta["counts"]["nodes"],
            "edges": n_edges,
            "ways": meta["counts"]["ways"],
            "length_km": round(total_km, 1),
            "bytes": len(blob),
            "gzip_bytes": len(gzip.compress(blob, compresslevel=6, mtime=0)),
        },
        "connectivity": {k: round(v, 4) for k, v in graph.component.items()},
        "edges_by_highway": {
            k: {"edges": by_kind[k], "km": round(km_by_kind[k], 1)}
            for k in sorted(by_kind, key=lambda k: (-km_by_kind[k], k))
        },
        "features": {
            k: {"edges": feat[k], "km": round(km[k], 2)}
            for k in (
                "building_passage",
                "corridor",
                "covered",
                "through_building",
                "may_close",
                "steps",
                "park_path",
                "unpaved",
                "lit",
                "informal",
            )
        },
        "steps": {
            "total_steps": feat["steps_total"],
            "estimated_edges": feat["steps_estimated_edges"],
        },
        "distinct": {
            "parks_on_paths": len(parks),
            "buildings_passed_through": len(passage_buildings),
            "venues": dict(sorted(venues.items())),
        },
        "exclusions": {
            "ways_by_reason": dict(sorted(graph.data.way_reasons.items())),
            "segments_dropped": dict(sorted(graph.dropped.items())),
            "dropped_examples": graph.dropped_examples,
            "nodes_excluded": dict(sorted(graph.excluded_nodes.items())),
        },
    }


def render_markdown(stats: dict) -> str:
    g, c = stats["graph"], stats["connectivity"]
    lines = [
        f"# Graph stats: {stats['city']}",
        "",
        "Generated by `python -m bdgraph.build`. Don't edit by hand.",
        "",
        "## Size and connectivity",
        "",
        "| | |",
        "|---|---|",
        f"| Nodes / edges / ways | {g['nodes']:,} / {g['edges']:,} / {g['ways']:,} |",
        f"| Walkable length | {g['length_km']:,} km |",
        f"| graph.bin | {g['bytes'] / 1e6:.2f} MB ({g['gzip_bytes'] / 1e6:.2f} MB gzipped) |",
        f"| Largest strongly connected component | {c['node_share']:.1%} of junctions, "
        f"{c['length_share']:.1%} of length (the rest is dropped) |",
        "",
        "## Fun features",
        "",
        "| Feature | Edges | km |",
        "|---|---:|---:|",
    ]
    for k, v in stats["features"].items():
        lines.append(f"| {k.replace('_', ' ')} | {v['edges']:,} | {v['km']:,} |")
    s, d = stats["steps"], stats["distinct"]
    lines += [
        "",
        f"Steps: {s['total_steps']:,} in total; {s['estimated_edges']:,} staircase edges have "
        "no `step_count` and are estimated from length.",
        f"Distinct parks with paths: {d['parks_on_paths']:,}. Buildings passed through via mapped "
        f"passages: {d['buildings_passed_through']:,}. Venues: {d['venues']}.",
        "",
        "## Edges by highway type",
        "",
        "| highway | Edges | km |",
        "|---|---:|---:|",
    ]
    for k, v in stats["edges_by_highway"].items():
        lines.append(f"| {k} | {v['edges']:,} | {v['km']:,} |")
    ex = stats["exclusions"]
    lines += ["", "## Safety exclusions", "", "Ways with a `highway` tag, by outcome:", ""]
    lines += [f"- `{k}`: {v:,}" for k, v in ex["ways_by_reason"].items()]
    lines += ["", "Segments of walkable ways dropped:", ""]
    for k, v in ex["segments_dropped"].items():
        sample = ", ".join(
            f"[{w}](https://www.openstreetmap.org/way/{w})"
            for w in ex["dropped_examples"].get(k, [])
        )
        lines.append(f"- `{k}`: {v:,} (e.g. ways {sample})")
    if not ex["segments_dropped"]:
        lines.append("- none")
    lines += ["", "Nodes routes may never pass through:", ""]
    lines += [f"- `{k}`: {v:,}" for k, v in ex["nodes_excluded"].items()] or ["- none"]
    return "\n".join(lines) + "\n"


def write_stats(graph: Graph, out_dir: Path, *, graph_bytes: int, docs_dir: Path | None = None):
    blob = (out_dir / "graph.bin").read_bytes()
    assert len(blob) == graph_bytes
    stats = compute_stats(graph, blob)
    target = docs_dir or Path("data") / graph.city.id
    target.mkdir(parents=True, exist_ok=True)
    (target / "stats.json").write_text(json.dumps(stats, indent=2, sort_keys=False) + "\n")
    (target / "STATS.md").write_text(render_markdown(stats))
    return stats
